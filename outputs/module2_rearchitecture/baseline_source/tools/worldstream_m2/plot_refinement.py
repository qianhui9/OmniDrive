"""Standalone data-driven refinement plots; no unexecuted or partial runs in summaries."""
import json
import numpy as np
from pathlib import Path
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from .refinement_common import ROOT


def read(name):return json.loads((ROOT/name).read_text())


def save(fig,name):
    fig.tight_layout()
    for ext in ('pdf','png'):fig.savefig(ROOT/'figures'/f'{name}.{ext}',bbox_inches='tight',dpi=300)
    plt.close(fig)


def main():
    plt.rcParams.update({'font.family':'serif','font.size':10,'axes.spines.top':False,'axes.spines.right':False})
    rows=read('block_benchmark.json')['rows']
    fig,axes=plt.subplots(1,2,figsize=(8,3.2))
    for i,ax in enumerate(axes):
        data=[r for r in rows if r['block']==i]
        for method,style,label in [('full','--','Full'),('original',':','Original packed'),('optimized','-','Spatial packed')]:
            ax.plot([r['updated']/54*100 for r in data],[r['timing'][method]['gpu_ms'] for r in data],style,marker='o',markersize=3,label=label)
        ax.set_xlabel(f'Block {i}: updated windows (%)');ax.set_ylabel('Total GPU interval (ms)');ax.legend(frameon=False,fontsize=8)
    save(fig,'packing_latency')
    summary=read('summary.json');modes=['baseline','original','optimized','auto']
    fig,axes=plt.subplots(1,2,figsize=(8,3.2))
    for ax,key,label in [(axes[0],'complete_wall_ms','Complete VLM wall (ms)'),
                         (axes[1],'m2_extra_interval_ms','M2 extra GPU interval (ms)')]:
        values=np.asarray([summary['real_'+m][key] for m in modes])
        ax.bar(modes,values[:,0],yerr=[np.zeros(4),values[:,1]-values[:,0]],capsize=3)
        ax.set_ylabel(label);ax.tick_params(axis='x',rotation=15)
    save(fig,'real_latency')
    data=read('real_m1_diagnosis.json')['per_frame']
    protocol=read('protocol.json')['scenes'];heat=[]
    for scene in protocol:
        frames=[f for f in data if any(f['frame_id']==x for x in scene['sample_ids'])]
        values=[]
        for f in frames:
            values.append([w['stable']/w['valid_tokens'] for c in f['m1_windows'].values() for w in c['windows']])
        heat.append(np.mean(values,axis=0))
    fig,(ax,archive_ax)=plt.subplots(1,2,figsize=(10,3))
    im=ax.imshow(heat,vmin=0,vmax=1,aspect='auto',cmap='Blues')
    ax.set_yticks(range(4));ax.set_yticklabels([s['category'] for s in protocol]);ax.set_xlabel('Camera-major attention window (9 per camera)')
    ax.set_xlabel('New scenes: camera-major window')
    archive=read('archived_m1_spatial_diagnosis.json')
    archive_heat=[[w['stable']/w['valid_tokens'] for c in row['cameras'].values() for w in c['windows']] for row in archive['rows']]
    archive_ax.imshow(archive_heat,vmin=0,vmax=1,aspect='auto',cmap='Blues')
    archive_ax.set_xlabel('Archived original scene: camera-major window')
    archive_ax.set_yticks(range(4));archive_ax.set_yticklabels([f'frame {i}' for i in range(4)])
    for item in (ax,archive_ax):
        for x in [8.5,17.5,26.5,35.5,44.5]:item.axvline(x,color='gray',linewidth=.5)
    fig.colorbar(im,ax=[ax,archive_ax],label='Stable patch fraction',fraction=.03,pad=.03)
    fig.subplots_adjust(right=.88,wspace=.3)
    for ext in ('pdf','png'):fig.savefig(ROOT/'figures'/f'm1_window_coverage.{ext}',bbox_inches='tight',dpi=300)
    plt.close(fig)
    q=read('task_quality.json')['worst_feature_locations']
    latest=read('quality_audit_results.json')
    if latest.get('output_layout_preserved'):
        q=[r for r in latest['quality'] if r.get('input_case')=='changed' and r['mode']=='optimized' and r['actual_skipped_windows']>0]
    else:
        allq=read('e2e_latency.json')['quality']
        q=[r for r in allq if r['controlled'] and r['mode']=='optimized' and r['repeat']==1 and r['actual_skipped_windows']>0]
    fig,axes=plt.subplots(1,2,figsize=(8,3.2))
    axes[0].scatter([r['actual_skipped_windows'] for r in q],[r['feature']['max_abs'] for r in q])
    axes[0].set_xlabel('Early window evaluations actually skipped');axes[0].set_ylabel('Final EVA maximum absolute error')
    axes[1].scatter([r['feature']['max_abs'] for r in q],[r['detection'].get('max_center_difference_m') or 0 for r in q])
    axes[1].axhline(.01,linestyle='--',color='gray',label='Frozen 1 cm regression target')
    axes[1].set_xlabel('Final EVA maximum absolute error');axes[1].set_ylabel('Matched detection centre difference (m)')
    axes[1].legend(frameon=False,fontsize=8);save(fig,'controlled_quality')
    (ROOT/'figures/captions.md').write_text('''All plots are generated by tools/worldstream_m2/plot_refinement.py from recorded JSON.

packing_latency: RTX 3090, production weights, each block/shape independently measured; n=20 after 5 warmups; medians include all packing/cache/scatter and launch gaps. One seeded mask per count, no interpolation guarantee.

real_latency: four independent nuScenes scenes, 16 unique time-ordered input frames, two measured replays after one warmup, 32 frame timings per arm; Latin-square mode rotation. Bars P50, upper caps P95, including reset frames. Includes all M1/M2 and actual greedy LLM; original/optimized/auto are real M1 integration, not synthetic sparse speedups.

m1_window_coverage: left, new four-scene per-window stable-patch fraction averaged over four chronological frames per scene; right, separately labelled reanalysis of four preserved original-scene masks, not newly measured timings. Camera order is preserved, nine windows per camera. No observation candidate is a deep feature equality certificate.

controlled_quality: two scenes with six unique synthetic changed inputs, one final output-layout-corrected audit execution; actual full OmniDrive and nonzero window skipping. The 1cm target was frozen before controlled outputs. This is a short regression test, not official task AP, broad driving QA or road-safety certification. Text/planning/memory/map results are separately reported.
''')


if __name__=='__main__':main()
